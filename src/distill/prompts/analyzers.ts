export const MEMORIES_ANALYZER_PROMPT = `# Memories 分析任务

你将收到 **{name}** 的原材料（聊天记录、照片时间线、社交媒体、其它文件）。
从中提取他们的共同记忆与关系动态，用于构建 Memories。

**原则：只提取有据可查的内容，不推断。没有依据就标注「原材料不足」。对感情细节保持温柔与尊重。**

---

## 提取维度

### 1. 关系时间线
从原材料中识别关键节点：
- 重要日期（第一次约会、在一起的日子、纪念日、分手日期）
- 里程碑（第一次说「我爱你」、见家长、同居、重要旅行）
- 转折点（重大争吵、冷战、复合、感情淡化的节点）
- 频繁提到的时间段或季节（「那年冬天」「大三的夏天」）

输出字段：重要日期 / 里程碑 / 转折点

### 2. 共同日常与仪式
- 固定活动（周末做什么、晚上怎么过）
- 共同爱好（一起看的剧、一起玩的游戏、共同的兴趣）
- 专属仪式（每天的晚安消息、特定纪念日的庆祝方式）
- 只有你们懂的东西（inside jokes、专属昵称、暗号、梗）

输出字段：日常活动 / 共同爱好 / 专属仪式 / 专属语言

### 3. 她的偏好
**吃**：喜欢吃什么 / 不吃什么；常去的餐厅 / 外卖偏好；特殊饮食习惯（奶茶口味、咖啡偏好）
**玩**：喜欢去的地方；旅行风格（计划型 / 随性，自然 / 城市）；娱乐偏好（电影类型、音乐口味）
**送礼**：喜欢收到什么样的礼物；送礼风格（实用 / 浪漫 / 精心准备 / 随缘）；对仪式感的态度

输出字段：吃 / 玩 / 送礼

### 4. 冲突与修复模式
- 常见争吵话题（什么事容易吵起来）
- 争吵升级模式（谁先发火、怎么升级、关键触发句）
- 冷战模式（谁先不说话、冷战多久、怎么打破）
- 修复方式（谁先道歉、和好的信号、需要什么才能原谅）
- 反复出现的未解决问题

输出字段：常见导火索 / 升级模式 / 冷战特点 / 修复方式

### 5. 情感动态
- 她开心时的表现（怎么表达开心、什么让她最高兴）
- 她难过时的表现（怎么表达不开心、需要什么样的安慰）
- 她生气时的表现（怎么表达生气、关键信号）
- 她想你时的表现（怎么表达思念、什么时候会主动联系）
- 她的情感需求（最需要被满足的是什么）

输出字段：开心时 / 难过时 / 生气时 / 想你时 / 核心需求

---

## 输出要求

- 语言：中文
- 没有信息的维度：标注「（原材料不足，建议追加聊天记录）」
- 有原文依据的结论：加引号标注原话
- 要求具体有画面感，不要写「可能」「大概」这类模糊表述
- 对感情内容保持温柔，不评价对错

---

## 本次原材料

{knowledge}
`;

