import type { ISODate, UUID } from './common';

/**
 * ★★ 朋友圈动态（2026-10-04 新增）。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 这是什么
 * ═══════════════════════════════════════════════════════════════════════════
 * 一个轻量的「时间线」：用户和角色都可以发动态，按时间倒序浏览。
 *
 * ★ 与「聊天记录」的关系（**这是本模块最需要想清楚的一点**）：
 *   两者都是文本，但**语义完全不同**，所以不做复用：
 *   - 聊天记录 = **一对一的对话**，有来有回，属于某个 `sessionId`，
 *     会进上下文窗口、会被记忆库检索、会参与 token 预算；
 *   - 动态 = **一个人对外的广播**，没有回复关系、不属于任何会话，
 *     **不应该**被自动塞进对话上下文（否则"她今天发了条动态"会变成
 *     "她刚才对你说了这句话"，把广播读成对话，是明显的人格错误）。
 *   ⇒ 单独一张表、单独一套类型。**刻意**不加 `sessionId`，
 *     让"动态不属于任何会话"成为类型层面的事实，而不是注释里的约定。
 *
 * ★ 为什么作者用 `authorId` + `authorName` **两个**字段（有冗余）：
 *   `authorId` 用于「只看某人的动态」与删除权限判断；
 *   `authorName` 是**发布当时的快照** —— 角色卡改名或被删除后，
 *   历史动态仍应显示当时那个名字。只存 id 就会变成"改名后历史全变"，
 *   只存名字则无法按人过滤。两个都存，各自服务一件事。
 */

/** 作者类型：本人 / 角色。用于「我的动态」与「她的动态」分区显示 */
export type MomentAuthorKind = 'user' | 'persona';

export interface Moment {
  id: UUID;
  /** 作者标识：本人固定为 `MOMENT_SELF_ID`；角色为其 persona id */
  authorId: string;
  authorKind: MomentAuthorKind;
  /** 发布时的作者名快照（改名/删卡后历史不受影响，见文件头） */
  authorName: string;
  /** 正文（发布时必填，去掉首尾空白后不得为空） */
  content: string;
  /**
   * 配图：**blob 逻辑路径**数组（不是 blob id，也不是 base64）。
   * ★ 存路径而不是 id：与 `blobRepo` 的 `path` 唯一索引一致，
   *   同一张图重复引用不会产生多份数据。
   * ★ 不存 base64：会让每条动态膨胀数百 KB，Dexie 记录一变胖，
   *   整个列表查询都会变慢（记录是整体读出来的）。
   */
  images: string[];
  /** 心情标签（自由文本，展示在正文下方；不参与检索） */
  mood?: string;
  /**
   * 点赞：存**点赞者标识**数组而不是一个计数。
   * ★ 为什么不用 `likeCount: number`：计数无法回答"我点过没有"，
   *   而"我点过没有"决定图标是实心还是空心 —— 于是还得再存一个 `likedByMe`，
   *   两个字段就有不一致的可能（点了两次、或计数没同步）。
   *   数组天然幂等（`Set` 语义），一个字段表达完整状态。
   */
  likedBy: string[];
  createdAt: ISODate;
  updatedAt: ISODate;
}

/** 本人（用户）在动态里的作者标识。用一个不可能与 persona id 冲突的常量 */
export const MOMENT_SELF_ID = 'self';
