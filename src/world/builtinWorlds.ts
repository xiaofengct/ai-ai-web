/**
 * ★★ 内置世界：欣然的生活（**仅内置欣然版**播种）。
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * 这个文件是什么、为什么单独存在
 * ═══════════════════════════════════════════════════════════════════════════
 * 用户明确：**排班与世界逻辑只在内置版有；不内置版留导入窗口**。
 * 本文件就是"内置版内一份"的那个来源。
 *
 * 内容依据用户提供的 `virtual-world.md`（世界设定主文档）与 `SKILL.md`
 * （同一套设定的另一种写法，多出活跃时段与概率门）。
 * 核对报告见 `docs/15-内置欣然设定覆盖核对报告.md`。
 *
 * ── 为什么手写常量，而不是把 md 塞进来运行时解析 ─────────────────────
 * 理想做法是"把 md 原文 embed 进来，启动时跑 `parseWorldDoc`"（单一真源）。
 * 但 md 里有反引号（`` `(d mod 5) + 1` ``），塞进 TS 模板串要转义，
 * 且启动时解析**万一失败就等于内置版没有世界** —— 关键功能不该建立在
 * "运行时解析用户风格文档"这种会失手的东西上。
 * ⇒ 结构化参数（排班/时段/概率门）**显式写成常量**，一眼可审；
 *   世界书条目按同样的结构手写。
 *
 * ★ 防漂移：`scripts/qa/check-world-drift.mjs` 会把本文件与
 *   `scripts/qa/fixtures/world/`（**原始文档的副本，不入库**）**对账**，
 *   锚点/周期/时段/概率门对不上就报错。
 *   即"手写"不等于"可以随意漂"。
 *
 *   ★ 该副本目录**故意不入库**（它含真实地址等私人信息，见 `.gitignore` 的说明）。
 *     因此对账脚本做了**优雅降级**：素材缺失时打印说明并以 0 退出，不会崩。
 *     ⇒ 本地保留该目录即可跑完整对账；clone 本仓库的人拿到的是"跳过"而非"失败"。
 *
 * ── 与源文档的两处**有意差异**（都写在这里，不藏着）─────────────────
 *
 * **① 深夜静默的右端点写 `08:00` 而不是源文档的 `07:59`。**
 *   时间窗约定是**半开区间 `[from, to)`**（标准做法，无歧义）。
 *   源文档写「23:00–07:59 之间不主动发消息」，其**意图**是"静默到 08:00 恢复"。
 *   若照抄 `07:59` 配半开区间，07:59 这一分钟就**不是**静默的 —— 差一分钟，
 *   与文档意图不符。故写成 `08:00`：静默覆盖 23:00–07:59:59，08:00 起恢复。
 *   （`check-world-drift` 用**语义**断言这一点：07:59 静默、08:00 不静默。）
 *
 * **② 概率门取 60（约 40%），不取 SKILL.md 的 30（约 70%）。**
 *   源资料里这个值**自相矛盾**：`virtual-world.md` 与两份排障记录都写 60，
 *   只有 `SKILL.md` 写 30。按"多数一致 + 更保守（更少打扰）"取 60。
 *   ⇒ 这条**需要你确认**（见 docs/15 §3.1）：想要更勤就改成 30。
 *
 * ★ 另有一处**未采纳**：源资料要求每天 8 个整点（8/10/…/22）触发。
 *   本应用的主动消息是**间隔式 tick**（见 `proactive/scheduler.ts`），
 *   不是整点调度 ⇒ 整点列表无从落地，故未纳入。
 *   时段限制（静默 + 活跃窗）已用另一种方式表达，效果等价。
 */

