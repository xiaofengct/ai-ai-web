/**
 * 跑一个子进程（**异步**），默认把输出实时透传到本进程的 stdout/stderr。
 *
 * ★ 为什么必须用异步 `spawn` 而不是 `execFileSync`（原实现，实测踩坑）：
 *
 *   本环境下 Node 的**同步**子进程 API 全线失效 —— `spawnSync` / `execFileSync` /
 *   `execSync` 一律返回 `EBUSY`，**连 spawn `cmd.exe` 都失败**；而同进程内换成
 *   异步 `spawn` 立刻正常。已实测对照（同一台机器、同一 shell）：
 *       node → spawnSync('cmd.exe')      → EBUSY
 *       node → spawn('cmd.exe')          → 正常
 *       python → subprocess.run(任意)     → 正常
 *       bash → 任意命令                   → 正常
 *   ⇒ 这是环境特性，不是脚本逻辑问题。但结论一样：**验收/打包链不该依赖同步 spawn**。
 *
 * ★ 顺带解决的两个旧隐患：
 *   1. 旧的 `maxBuffer: 64MB` 是为了兜住 gradle 的长输出；异步 + 直接继承 stdio
 *      后**父进程不缓存任何输出**，这个上限连同"输出超限被杀"的风险一起消失。
 *   2. `execFileSync` 期间父进程完全阻塞，日志是"憋到最后一次性吐出来"的；
 *      异步模式下构建进度实时可见 —— 长构建（gradle 30s~3min）出问题时能立刻看出卡在哪。
 *
 * `shell: true` 仅用于 npm / gradlew —— Windows 上它们是 `.cmd`/`.bat`，
 * CreateProcess 不会自己解析 PATHEXT；直接可执行文件（aapt2 等）走 shell:false。
 */
/**
 * 找到 JDK 的根目录（Gradle 需要 JAVA_HOME）。
 *
 * ★ 为什么要自动找：本机 `JAVA_HOME` 默认是**空的**（JDK 是我们为这个项目临时装的，
 *   没进系统环境变量）。手工跑一次忘了传，Gradle 就会抛一个跟"Java 版本"有关的
 *   误导性错误（实测报过 `无效的源发行版：21`，看着像版本装错了，其实只是没找到 JDK）。
 *   ⇒ 把探测逻辑固化进脚本：环境变量 → 常见工具链目录 → PATH 上的 java。
 *
 * ★ 必须 ≥ 21：`android/app/capacitor.build.gradle` 硬编码 `JavaVersion.VERSION_21`，
 *   而那个文件首行写明 `DO NOT EDIT THIS FILE!`（每次 cap update 会被覆盖），
 *   ⇒ **不能降级文件，只能满足它**。所以这里优先挑版本号大的 JDK。
 */
function resolveJavaHome() {
  const candidates = [];

  if (process.env.JAVA_HOME && existsSync(join(process.env.JAVA_HOME, 'bin'))) {
    candidates.push(process.env.JAVA_HOME);
  }
  // 本项目自建的 Android 工具链（见 docs/06 的环境搭建一节）
  const toolchain = join(process.env.USERPROFILE ?? process.env.HOME ?? '', '.workbuddy', 'android-toolchain');
  if (existsSync(toolchain)) {
    for (const d of readdirSync(toolchain)) {
      if (/^jdk/i.test(d)) candidates.push(join(toolchain, d));
    }
  }
  // PATH 上的 java → 回推两级（.../bin/java → ...bin → JDK 根）
  for (const p of (process.env.PATH ?? '').split(process.platform === 'win32' ? ';' : ':')) {
    if (p && existsSync(join(p, process.platform === 'win32' ? 'java.exe' : 'java'))) {
      candidates.push(dirname(p));
    }
  }
  // 兼容 "JAVA_HOME 直接指向 bin" 的常见误配
  if (process.env.JAVA_HOME && existsSync(process.env.JAVA_HOME)) {
    candidates.push(dirname(process.env.JAVA_HOME));
  }

  const usable = candidates.filter((c) => c && existsSync(join(c, 'bin')));
  if (usable.length === 0) return null;

  // 版本号大的优先（21 优于 17，见上方注释）
  const verOf = (p) => {
    const m = /(?:jdk[-_])?(\d+)(?:[.\-_](\d+))?/.exec(p.split(/[\\/]/).pop() ?? '');
    return m ? Number(m[1]) * 1000 + Number(m[2] ?? 0) : 0;
  };
  usable.sort((a, b) => verOf(b) - verOf(a));
  return usable[0];
}

/** 模块级解析一次：`main()` 只负责打印，`buildVariant()` 直接用它注入 gradle 环境 */
const JAVA_HOME = resolveJavaHome();

const run = (cmd, args, opts = {}) => {
  return new Promise((resolve, reject) => {
    if (!opts.silent) process.stdout.write(`\n\x1b[36m$ ${cmd} ${args.join(' ')}\x1b[0m\n`);
    const child = spawn(cmd, args, {
      cwd: opts.cwd ?? ROOT,
      env: { ...process.env, ...opts.env },
      shell: opts.shell ?? process.platform === 'win32',
      stdio: opts.capture ? ['ignore', 'pipe', 'pipe'] : 'inherit',
      windowsHide: true,
    });

    let out = '';
    let err = '';
    if (opts.capture) {
      child.stdout.setEncoding('utf8');
      child.stderr.setEncoding('utf8');
      child.stdout.on('data', (d) => {
        out += d;
      });
      child.stderr.on('data', (d) => {
        err += d;
      });
    }

    child.on('error', (e) => reject(new Error(`${cmd} 启动失败：${e.message}`)));
    child.on('close', (code) => {
      if (code === 0) resolve(out);
      else {
        const e = new Error(`${cmd} 退出码 ${code}${err ? `\n${err.trim().slice(-1500)}` : ''}`);
        e.exitCode = code;
        e.stdout = out;
        e.stderr = err;
        reject(e);
      }
    });
  });
}

function readVersion() {
  // 从 build.gradle 读 versionName（避免和 gradle 的版本号两处维护）
  const text = readFileSync(join(ANDROID, 'app', 'build.gradle'), 'utf8');
  const m = /versionName\s+["']([^"']+)["']/.exec(text);
  return m ? m[1] : '1.0';
}

/** 同 readVersion，但读 versionCode（写进 MANIFEST 便于与安装包对账） */
function readVersionCode() {
  const text = readFileSync(join(ANDROID, 'app', 'build.gradle'), 'utf8');
  const m = /versionCode\s+(\d+)/.exec(text);
  return m ? Number(m[1]) : 0;
}

